def test_report_to_dict_roundtrip():
    report = diagnose(
        iptables_available=True, nft_available=True,
        reported_mode="nft", alternatives_mode="legacy",
        legacy_rule_lines=None, nft_rule_lines=None,
    )
    d = report.to_dict()
    assert d["status"] == STATUS_ALTERNATIVES_MISMATCH
    assert d["reported_mode"] == "nft"
    assert d["alternatives_mode"] == "legacy"


def test_diagnose_host_integration():
    def fake_runner(cmd, timeout=15):
        if cmd[0] == "which":
            return "/usr/sbin/" + cmd[1] + "\n"
        if cmd == ["iptables", "--version"]:
            return "iptables v1.8.11 (nf_tables)\n"
        if cmd == ["update-alternatives", "--display", "iptables"]:
            return "  link currently points to /usr/sbin/iptables-nft\n"
        if cmd == ["iptables-legacy-save"]:
            return "# Generated\n"
        return ""

    report = diagnose_host(runner=fake_runner)
    assert report.status == STATUS_OK
    assert report.legacy_rule_lines == 0
